/// Retrieves the 8x16 glyph for an ASCII byte (falls back to Space for non-printable).
#[inline(always)]
pub fn get_glyph_8x16(ch: u8) -> &'static [u8; 16] {
    if (32..=126).contains(&ch) {
        &FONT_8X16[(ch - 32) as usize]
    } else {
        &FONT_8X16[0] // fallback to space
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_font_constants() {
        assert_eq!(FONT_W, 8);
        assert_eq!(FONT_H, 16);
        assert_eq!(FONT_8X16.len(), 95);
    }

    #[test]
    fn test_glyph_lookup_properties() {
        let space = get_glyph_8x16(b' ');
        assert!(space.iter().all(|&b| b == 0));

        let a = get_glyph_8x16(b'A');
        assert!(a.iter().any(|&b| b != 0));

        let out_of_bounds = get_glyph_8x16(200);
        assert_eq!(out_of_bounds, space);
    }

    #[test]
    fn test_descenders_and_ascenders() {
        // 'g' should have active bits below baseline (row 11)
        let g = get_glyph_8x16(b'g');
        assert_ne!(g[11], 0);

        // 'd' should have active bits in ascender region (row 1..3)
        let d = get_glyph_8x16(b'd');
        assert_ne!(d[1], 0);
    }
}
